/**
 * Writes src/utils/pokemon/national-dex.ts: the national dex number of every species in
 * pokemonNames, read from the per-game pokedex files in public/data/pokedex/.
 *
 *   npx tsx scripts/generate-national-dex.ts
 *
 * The app needs a species' generation without loading a game's pokedex (the species roster
 * editor offers every species, whatever the tierlist's game), so the numbers are baked into
 * a small static table. Run by `npm run sync-pokedex` after it refreshes the data files.
 */
import * as fs from 'fs'
import * as path from 'path'
import { fileURLToPath } from 'url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..') + path.sep
const OUT_FILE = ROOT + 'src/utils/pokemon/national-dex.ts'

const { pokemonNames, getSpeciesRootName } = await import('../src/utils/pokemon.ts')

;(globalThis as any).window = globalThis
const dataDir = ROOT + 'public/data/pokedex/'
for (const f of fs.readdirSync(dataDir)) {
  if (f.endsWith('.js')) (0, eval)(fs.readFileSync(dataDir + f, 'utf8'))
}

/** Same spelling-insensitive key as normalizeSpeciesKey in src/utils/pokemon/pokedex.ts. */
function normalize(name: string): string {
  return name
    .normalize('NFD')
    .replace(/\p{Diacritic}/gu, '')
    .replace(/♀/g, 'f')
    .replace(/♂/g, 'm')
    .toLowerCase()
    .replace(/[^a-z0-9]/g, '')
}

const dexBySpecies = new Map<string, number>()
for (const section of Object.values((globalThis as any).pokedexData as Record<string, Record<string, any>>)) {
  for (const entry of Object.values(section)) {
    const num = entry.national_dex_number
    if (typeof num !== 'number' || !entry.species) continue
    const key = normalize(entry.species)
    if (!dexBySpecies.has(key)) dexBySpecies.set(key, num)
  }
}

const table: [string, number][] = []
const missing: string[] = []
const seen = new Set<string>()
for (const name of pokemonNames) {
  const root = getSpeciesRootName(name)
  if (seen.has(root)) continue
  seen.add(root)
  const num = dexBySpecies.get(normalize(root))
  if (num === undefined) missing.push(root)
  else table.push([root, num])
}
if (missing.length) {
  console.error(`No national dex number for: ${missing.join(', ')}`)
  process.exit(1)
}
table.sort((a, b) => a[1] - b[1] || a[0].localeCompare(b[0]))

const body = table.map(([name, num]) => `    ${JSON.stringify(name)}: ${num},`).join('\n')
fs.writeFileSync(OUT_FILE,
  `// Generated by scripts/generate-national-dex.ts from public/data/pokedex — do not edit.\n` +
  `\n` +
  `/** National dex number of every species in pokemonNames, keyed by getSpeciesRootName. */\n` +
  `export const NATIONAL_DEX: Record<string, number> = {\n${body}\n};\n`)
console.log(`Wrote ${table.length} species to ${path.relative(ROOT, OUT_FILE)}`)
