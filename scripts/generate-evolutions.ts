/**
 * Writes src/utils/pokemon/evolutions.ts: the species each species evolves from, read from
 * PokeAPI's pokemon_species.csv (`evolves_from_species_id`) and keyed by the app's names.
 *
 *   npx tsx scripts/generate-evolutions.ts [path/to/pokemon_species.csv]
 *
 * Without a path the CSV is downloaded from the PokeAPI repo. The per-game pokedex files do
 * carry an `evolution_family`, but it is unordered (Snorlax's lists Snorlax before Munchlax)
 * so it cannot say which stage is the highest; this table can. Species are joined on their
 * national dex number, so run it after generate-national-dex.ts when new species are added.
 */
import * as fs from 'fs'
import * as path from 'path'
import { fileURLToPath } from 'url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..') + path.sep
const OUT_FILE = ROOT + 'src/utils/pokemon/evolutions.ts'
const CSV_URL = 'https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/pokemon_species.csv'

const { NATIONAL_DEX } = await import('../src/utils/pokemon/national-dex.ts')

const csvPath = process.argv[2]
const csv = csvPath ? fs.readFileSync(csvPath, 'utf8') : await (await fetch(CSV_URL)).text()

const nameByDex = new Map<number, string>()
for (const [name, num] of Object.entries(NATIONAL_DEX)) nameByDex.set(num, name)

const [header, ...rows] = csv.trim().split(/\r?\n/)
const cols = header.split(',')
const idCol = cols.indexOf('id')
const fromCol = cols.indexOf('evolves_from_species_id')
if (idCol < 0 || fromCol < 0) {
  console.error('pokemon_species.csv is missing the id / evolves_from_species_id columns')
  process.exit(1)
}

const table: [string, string][] = []
for (const row of rows) {
  const cells = row.split(',')
  const from = Number(cells[fromCol])
  if (!from) continue
  const name = nameByDex.get(Number(cells[idCol]))
  const fromName = nameByDex.get(from)
  // Species the app doesn't list (yet) are skipped rather than failing the run.
  if (name && fromName) table.push([name, fromName])
}
table.sort((a, b) => NATIONAL_DEX[a[0]] - NATIONAL_DEX[b[0]])

const body = table.map(([name, from]) => `    ${JSON.stringify(name)}: ${JSON.stringify(from)},`).join('\n')
fs.writeFileSync(OUT_FILE,
  `// Generated by scripts/generate-evolutions.ts from PokeAPI pokemon_species.csv — do not edit.\n` +
  `\n` +
  `/** The species each species evolves from, keyed by getSpeciesRootName. Base stages are absent. */\n` +
  `export const EVOLVES_FROM: Record<string, string> = {\n${body}\n};\n`)
console.log(`Wrote ${table.length} evolutions to ${path.relative(ROOT, OUT_FILE)}`)
